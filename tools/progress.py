#!/usr/bin/env python3
"""
decomp progress: bytes of game code decompiled into src/ divided by total game code bytes.

usage: tools/progress.py [--readme]
  --readme  also writes the result into README.md between the progress markers
"""
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FUNCTIONS = ROOT / "progress" / "functions.csv"
DONE = ROOT / "progress" / "done.txt"
PLATFORM = ROOT / "progress" / "platform.csv"
README = ROOT / "README.md"

# address ranges in .text that hold the C runtime and Xbox system code (not ported, the Vita has its own).
# estimated from where library-identified functions cluster; tighten as the layout gets mapped.
LIB_RANGES = [
    (0x000178CF, 0x0001E72A),
    (0x00278930, 0x00283EA0),
    (0x002BE0FD, 0x002BF8D2),
]

# names from the xbox symbol database that mark system code outside the ranges above
LIB_PREFIXES = ("XAPILIB::", "XGRAPHICS::", "XONLINES::", "D3D8::", "D3D8LTCG::", "DSOUND::", "xboxkrnl.exe::")


def is_lib(address, name):
    return any(lo <= address < hi for lo, hi in LIB_RANGES) or name.startswith(LIB_PREFIXES)


def load_platform():
    """xbox-only engine code the port replaces, generated by tools/platform.sh."""
    if not PLATFORM.exists():
        return set()
    with PLATFORM.open() as f:
        return {int(row["address"], 16) for row in csv.DictReader(f)}


def load_done():
    if not DONE.exists():
        return set()
    done = set()
    for line in DONE.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            done.add(int(line.split()[0], 16))
    return done


def main():
    done = load_done()
    platform = load_platform()
    total_bytes = done_bytes = total_funcs = done_funcs = 0
    known = set()

    with FUNCTIONS.open() as f:
        for row in csv.DictReader(f):
            address = int(row["address"], 16)
            if is_lib(address, row["name"]) or address in platform:
                continue
            size = int(row["size"])
            known.add(address)
            total_bytes += size
            total_funcs += 1
            if address in done:
                done_bytes += size
                done_funcs += 1

    unknown = done - known
    if unknown:
        print("warning: done.txt has addresses that aren't game functions: " + ", ".join(f"{a:08x}" for a in sorted(unknown)))

    percent = 100 * done_bytes / total_bytes
    summary = (
        f"**{percent:.2f}%** decompiled "
        f"({done_bytes:,} / {total_bytes:,} bytes, {done_funcs:,} / {total_funcs:,} functions)"
    )
    print(summary.replace("**", ""))

    if "--readme" in sys.argv:
        text = README.read_text()
        new = re.sub(
            r"(<!-- progress -->).*?(<!-- /progress -->)",
            lambda m: f"{m.group(1)}\n{summary}\n{m.group(2)}",
            text,
            flags=re.S,
        )
        if new == text and summary not in text:
            sys.exit("error: progress markers not found in README.md")
        README.write_text(new)


if __name__ == "__main__":
    main()
