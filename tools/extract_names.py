#!/usr/bin/env python3
"""
reads the hardcoded engine names out of FName::StaticInit and writes src/Core/Inc/UnNames.h.

each name is set up by a call to FNameEntry allocation with the string in ecx, the index in edx
and the flags pushed on the stack, so this walks the disassembly and tracks those values.

usage: tools/extract_names.py
"""
import re
import struct
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
XBE = ROOT / "game" / "Default.xbe"
OUT = ROOT / "src" / "Core" / "Inc" / "UnNames.h"
STATIC_INIT = "00092afc"
ALLOCATE_ENTRY = "0x000925d3"
RF_HIGHLIGHTED = 0x400


def read_strings():
    d = XBE.read_bytes()
    u32 = lambda o: struct.unpack_from("<I", d, o)[0]
    base = u32(0x104)
    sections = []
    for i in range(u32(0x11C)):
        _, va, _, raw, rsize, _ = struct.unpack_from("<IIIIII", d, u32(0x120) - base + i * 0x38)
        sections.append((va, rsize, raw))

    def cstr(va):
        for sva, rsize, raw in sections:
            if sva <= va < sva + rsize:
                r = raw + va - sva
                return d[r:d.index(b"\0", r)].decode("latin-1")

    return cstr


def main():
    cstr = read_strings()
    asm = subprocess.run([str(ROOT / "tools" / "ghidra.sh"), "Disasm.java", STATIC_INIT],
                         capture_output=True, text=True, check=True).stdout.splitlines()[1:]

    regs, stack, names = {}, [], []
    for line in asm:
        op, _, args = line.split("  ", 1)[1].split("  ;", 1)[0].partition(" ")
        a = [x.strip() for x in args.split(",")] if args else []

        def value(x):
            if x in regs:
                return regs[x]
            return int(x, 16) if x.startswith("0x") else int(x) if x.isdigit() else None

        if op == "MOV" and len(a) == 2:
            regs[a[0]] = value(a[1])
        elif op == "XOR" and a[0] == a[1]:
            regs[a[0]] = 0
        elif op == "INC":
            regs[a[0]] = (regs.get(a[0]) or 0) + 1
        elif op == "PUSH":
            stack.append(value(a[0]))
        elif op == "POP":
            regs[a[0]] = stack.pop() if stack else None
        elif op == "CALL" and a[0] == ALLOCATE_ENTRY:
            names.append((regs["EDX"], cstr(regs["ECX"]), stack[-1]))
            del stack[-2:]
        elif op == "CALL":
            stack.clear()

    names.sort()
    body = "\n".join(
        f"REGISTER_NAME({index:4d}, {name}, {'RF_HighlightedName' if flags & RF_HIGHLIGHTED else '0'})" for index, name, flags in names
    )
    OUT.write_text(
        "// generated by tools/extract_names.py from FName::StaticInit, do not edit.\n"
        "// REGISTER_NAME(index, name, extra flags) for every name hardcoded into the engine.\n\n"
        "#ifndef REGISTER_NAME\n#define REGISTER_NAME(num, name, flags)\n#endif\n\n"
        f"{body}\n\n#undef REGISTER_NAME\n"
    )
    print(f"{len(names)} names written to {OUT}")


if __name__ == "__main__":
    main()
